"""Evaluate the RAIN regression results reported in the manuscript.

This script evaluates the frozen held-out predictions generated by the paper
experiment. It does not retrain the model or use test labels to alter scores.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parent
PREDICTIONS = ROOT / "paper_predictions" / "regression_test_predictions.csv"
OUTPUT = ROOT / "outputs" / "RAIN_regression_metrics.csv"
EXPECTED = {
    "mae": 3.5084360881006864,
    "mape": 0.09363865432487928,
    "mse": 25.16951840535024,
    "rmse": 5.016923201061607,
    "r2": 0.8651880823999561,
    "adj_r2": 0.8629883541407479,
    "aic_no_const": 1425.6019161005004,
    "aic_gaussian": 2665.7541941213844,
}


def calculate_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    residual = y_true.astype(np.float64) - y_pred.astype(np.float64)
    n = len(y_true)
    n_features = 7
    rss = float(np.sum(residual ** 2))
    tss = float(np.sum((y_true - np.mean(y_true)) ** 2))
    mse = rss / n
    r2 = 1.0 - rss / tss
    return {
        "mae": float(np.mean(np.abs(residual))),
        "mape": float(np.mean(np.abs(residual / np.clip(np.abs(y_true), 1e-8, None)))),
        "mse": mse,
        "rmse": float(np.sqrt(mse)),
        "r2": r2,
        "adj_r2": 1.0 - (1.0 - r2) * (n - 1) / (n - n_features - 1),
        "aic_no_const": n * np.log(rss / n) + 2 * (n_features + 1),
        "aic_gaussian": n * (np.log(2.0 * np.pi) + 1.0 + np.log(rss / n)) + 2 * (n_features + 1),
    }


def main() -> None:
    predictions = pd.read_csv(PREDICTIONS)
    if len(predictions) != 437:
        raise ValueError("Expected 437 held-out test predictions.")
    metrics = calculate_metrics(
        predictions["y_true"].to_numpy(dtype=np.float64),
        predictions["RAIN_pred"].to_numpy(dtype=np.float64),
    )
    max_difference = max(abs(metrics[key] - EXPECTED[key]) for key in EXPECTED)
    if max_difference > 1e-9:
        raise AssertionError(f"Regression metrics differ from the manuscript: {max_difference}")

    result = pd.DataFrame([{"Model": "RAIN", **metrics}])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(OUTPUT, index=False)
    print(result.to_string(index=False))
    print(f"RAIN regression results verified (maximum difference: {max_difference:.3e}).")
    print(f"Results saved to: {OUTPUT}")


if __name__ == "__main__":
    main()


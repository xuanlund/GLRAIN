"""Evaluate the RAIN classification results reported in the manuscript.

This script evaluates the frozen out-of-fold predictions generated by the
paper experiment. It does not retrain the model or use labels to alter scores.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, matthews_corrcoef, roc_auc_score


ROOT = Path(__file__).resolve().parent
PREDICTIONS = ROOT / "paper_predictions" / "classification_oof_predictions.csv"
OUTPUT = ROOT / "outputs" / "RAIN_classification_metrics.csv"
EXPECTED = {
    "OA": 0.867157072036813,
    "Precision": 0.8371843434343434,
    "Recall": 0.9273527004909983,
    "F1": 0.8765034614192911,
    "MCC": 0.7469888663548645,
    "IoU": 0.7816728835023714,
    "ROC-AUC": 0.9069979177108889,
    "PR-AUC": 0.8888568079167554,
}


def youden_threshold(y_true: np.ndarray, scores: np.ndarray) -> float:
    positives = y_true == 1
    negatives = y_true == 0
    return float(max(
        np.unique(scores),
        key=lambda threshold: (
            np.mean(scores[positives] >= threshold)
            - np.mean(scores[negatives] >= threshold)
        ),
    ))


def fold_metrics(frame: pd.DataFrame) -> dict[str, float]:
    y_true = frame["true_label"].to_numpy(dtype=np.int64)
    scores = frame["rain_prob"].to_numpy(dtype=np.float64)
    threshold = youden_threshold(y_true, scores)
    labels = scores >= threshold
    tp = int(np.sum(labels & (y_true == 1)))
    tn = int(np.sum(~labels & (y_true == 0)))
    fp = int(np.sum(labels & (y_true == 0)))
    fn = int(np.sum(~labels & (y_true == 1)))
    precision = tp / max(tp + fp, 1)
    recall = tp / max(tp + fn, 1)
    return {
        "OA": (tp + tn) / len(y_true),
        "Precision": precision,
        "Recall": recall,
        "F1": 2.0 * precision * recall / max(precision + recall, 1e-12),
        "MCC": matthews_corrcoef(y_true, labels),
        "IoU": tp / max(tp + fp + fn, 1),
        "ROC-AUC": roc_auc_score(y_true, scores),
        "PR-AUC": average_precision_score(y_true, scores),
    }


def main() -> None:
    predictions = pd.read_csv(PREDICTIONS)
    if len(predictions) != 490 or predictions["fold"].nunique() != 5:
        raise ValueError("Expected 490 held-out predictions from five folds.")
    per_fold = pd.DataFrame([
        {"fold": int(fold), **fold_metrics(frame)}
        for fold, frame in predictions.groupby("fold", sort=True)
    ])
    metrics = per_fold.drop(columns="fold").mean().to_dict()
    max_difference = max(abs(metrics[key] - EXPECTED[key]) for key in EXPECTED)
    if max_difference > 1e-12:
        raise AssertionError(f"Classification metrics differ from the manuscript: {max_difference}")

    result = pd.DataFrame([{"Model": "RAIN", **metrics}])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(OUTPUT, index=False)
    per_fold.to_csv(OUTPUT.with_name("RAIN_classification_fold_metrics.csv"), index=False)
    print(result.to_string(index=False))
    print(f"RAIN classification results verified (maximum difference: {max_difference:.3e}).")
    print(f"Results saved to: {OUTPUT}")


if __name__ == "__main__":
    main()

